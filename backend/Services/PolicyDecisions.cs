using UWorldFreshdeskCopilot.Models;

namespace UWorldFreshdeskCopilot.Services;

// Small factory helpers so rules read cleanly.
public static class PolicyDecisions
{
    public static Decision Auto(PolicyAction action, string rule, double confidence,
        string reason, string customerEmailHtml) => new()
    {
        Action = action,
        Confidence = confidence,
        RuleName = rule,
        Reason = reason,
        CustomerEmailHtml = customerEmailHtml
    };

    public static Decision AgentReview(string rule, string reason, IEnumerable<string> steps) => new()
    {
        Action = PolicyAction.AgentReview,
        Confidence = 0.5,
        RuleName = rule,
        Reason = reason,
        SuggestedSteps = steps.Select((s, i) => new SuggestedStep { Order = i + 1, Text = s }).ToList()
    };

    public static List<SuggestedStep> Steps(params string[] steps) =>
        steps.Select((s, i) => new SuggestedStep { Order = i + 1, Text = s }).ToList();
}

public static class EmailTemplates
{
    public static string Wrap(string name, string body) => $@"
<p>Hi {name},</p>
{body}
<p>Warm regards,<br/>UWorld Support</p>
<p style=""color:#888;font-size:12px"">This reply was generated by UWorld Copilot.</p>";

    public static string PasswordReset(string name, string tempPassword) => Wrap(name, $@"
<p>We received your password reset request. We've set a temporary password on your account:</p>
<p style=""font-size:16px""><strong>{tempPassword}</strong></p>
<p>Please log in with it and change your password immediately under <em>Account &rarr; Security</em>.</p>");

    public static string RefundDenied(string name, string subscription, int usagePercent, int daysSince, int windowDays) => Wrap(name, $@"
<p>Thank you for reaching out about a refund for your <strong>{subscription}</strong> subscription.</p>
<p>After reviewing your account, we're unable to process a refund. Our records show the subscription
has been used ({usagePercent}% of content accessed) and the purchase was {daysSince} days ago, which is
outside our {windowDays}-day refund window.</p>
<p>Per our refund policy, subscriptions that have been actively used or are past the refund window are
not eligible for a refund. If you believe this is an error, reply to this email and a specialist will review.</p>");

    public static string RefundApproved(string name, string subscription, decimal amount) => Wrap(name, $@"
<p>Good news — we've approved your refund for the <strong>{subscription}</strong> subscription.</p>
<p>A refund of <strong>${amount:0.00}</strong> has been initiated and should appear on your original
payment method within 5–7 business days. Your subscription access has been cancelled.</p>");

    public static string DuplicateRefund(string name, decimal amount) => Wrap(name, $@"
<p>We noticed a duplicate charge on your account and have refunded the extra payment.</p>
<p>A refund of <strong>${amount:0.00}</strong> for the duplicate charge has been initiated and should
appear within 5–7 business days. Your subscription remains active.</p>");

    public static string AccountUnlocked(string name) => Wrap(name, $@"
<p>Your account was temporarily locked due to multiple failed login attempts. We've unlocked it.</p>
<p>You can now log in. If you've forgotten your password, use <em>Forgot password</em> on the login page.</p>");

    public static string CancellationBeforeActivation(string name, string subscription, decimal amount) => Wrap(name, $@"
<p>We've cancelled your <strong>{subscription}</strong> subscription as requested.</p>
<p>Since the subscription was not yet activated, a full refund of <strong>${amount:0.00}</strong> has
been initiated and should appear within 5–7 business days.</p>");
}
